def old_cpu(model: str) -> tuple[int, int, int, float] | None:
    """(поколение, ядра, потоки, турбо ГГц) старого Intel по названию модели."""
    # Ровно четыре цифры: пятизначные (i5-12450H, i3-1115G4) — 10-е поколение и новее, их здесь нет;
    # иначе «12450» читалось как 1-е поколение и каталог падал на BOOST[1]
    if (m := re.match(r"Core i([357])-(\d)(\d{3})(?!\d)", model)) and int(m[2]) in BOOST:
        tier, gen = int(m[1]), int(m[2])
        if model[-1] == "K" and gen == 5 or model.endswith("6850K"):        # HEDT 5820K/5930K/6850K
            return 5, 6, 12, 3.7
        cores = {3: 2, 5: 4, 7: 4}[tier] if gen <= 7 else {3: 4, 5: 6, 7: 6 if gen == 8 else 8}[tier]
        threads = cores * 2 if tier == 3 and gen <= 7 or tier == 7 and gen <= 8 else cores
        ghz = BOOST[gen] - (0.6 if model.endswith("T") else 0) + (0.3 if "K" in model else 0)
        return gen, cores, threads, ghz
    if m := re.match(r"Xeon E3-12(\d)(\d)(?: v(\d))?", model):
        gen = {None: 2, "1": 2, "2": 3, "3": 4, "5": 6, "6": 7}[m[3]]         # «v1» — то же, что без версии
        return gen, 4, 4 if m[1] == "2" else 8, BOOST[gen]         # 1220/1225 — без HT
    if m := re.match(r"Xeon E5-(\d{4}(?: v\d)?)", model):
        v = model[-1] if " v" in model else "1"
        gen = {"1": 2, "2": 3, "3": 4, "4": 5}[v]
        cores = XEON_E5_CORES.get(m[1], 8)
        return gen, cores, cores * 2, {"1": 3.3, "2": 3.4, "3": 3.4, "4": 3.3}[v]
    if m := re.match(r"(Pentium|Celeron) G(\d)(\d{3})", model):
        gen = {1: 2, 2: 3, 3: 4, 4: 6, 5: 8, 6: 10, 7: 12}[int(m[2])]
        if m[1] == "Celeron":               # у Celeron своя нумерация: G39xx, G49xx, G59xx, G69xx
            gen = {"3": 6, "4": 8, "5": 10, "6": 12}.get(m[2], gen) if m[3][0] == "9" else gen
        ht = m[1] == "Pentium" and not (m[2] == "4" and m[3] in ("400", "500"))
        return gen, 2, 4 if ht else 2, {2: 3.1, 3: 3.3, 4: 3.4, 6: 3.4, 8: 3.7, 10: 3.8, 12: 3.7}[gen]
    return None


def cpu_score(model: str | None, cores=None, threads=None, ghz=None) -> tuple[int, int] | None:
    """(игры, многопоток). Для старых — оценка по архитектуре; ядра/частота из карточек, если есть."""
    if not model:
        return None
    if model in CPU_SCORE:
        return CPU_SCORE[model]
    if not (o := old_cpu(model)):
        return None
    gen, c, t, g = o
    c, t, g = cores or c, threads or t, ghz or g
    ipc = IPC[gen]
    game = ipc * g / REF_GHZ * min(1, t / REF_THREADS) ** 0.35
    mt = ipc * g * (c + 0.25 * (t - c)) / REF_MT
    return round(game * 100), round(mt * 100)


