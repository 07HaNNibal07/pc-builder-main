def fps(game: dict, res: int, gpu: int, gpu_mem: int | None, cpu: int, dual: bool = True, memk: float = 1.0) -> dict:
    """Оценка среднего FPS. res — индекс в RES; gpu, cpu — баллы; memk — mem_k(). Возвращает fps и узкое место."""
    g = game["gpu"][res] * (gpu / 100) ** RES_K[res]
    if gpu_mem and gpu_mem < (need := game["vram"][res]):
        g *= (gpu_mem / need) ** VRAM_K
    c = game["cpu"] * cpu / 100 * (1 if dual else SINGLE_CHANNEL) * memk
    f = (g ** -SOFT_P + c ** -SOFT_P) ** (-1 / SOFT_P)
    return {"fps": round(f), "limit": "gpu" if g < c else "cpu",
            "vram": bool(gpu_mem and gpu_mem < game["vram"][res])}


def model_params() -> dict:
    """Параметры модели для веб-части: формула там повторяется, числа — отсюда."""
    return {"res": RES, "resK": RES_K, "p": SOFT_P, "vramK": VRAM_K, "single": SINGLE_CHANNEL, "ddr4": DDR4_K,
            "games": GAMES}
